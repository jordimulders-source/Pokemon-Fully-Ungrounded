S(28,(17,'1'),(18,19,'3'),(20,21,'4'),(22,'5'),(23,'2'))
S(29,(18,'1'),(19,20,'3'),(21,22,'4'),(23,'5'),(24,'2'))
# --- romp + bovenarm healer: één lichte massa linksboven, één schaduwband rechts/onder
