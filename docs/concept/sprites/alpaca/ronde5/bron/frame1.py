def build(spec):
    rows = [['.'] * 64 for _ in range(64)]
    for y, segs in spec.items():
        for x, s in segs:
            for i, ch in enumerate(s):
                if ch != ' ':
                    rows[y][x + i] = ch
    return rows


def write(path, frames):
    with open(path, 'w') as f:
        for k, rows in enumerate(frames):
            f.write('== frame %d\n' % (k + 1))
            for r in rows:
                f.write(''.join(r) + '\n')


