def SCHEEF(rows,off):
    """kolom c zakt off[c] rijen: zo ligt een recht object schuin (trapjes van 4)."""
    H=len(rows)+max(off); W=len(rows[0]); G=[['.']*W for _ in range(H)]
    for r,row in enumerate(rows):
        for c,ch in enumerate(row): G[r+off[c]][c]=ch
    return [''.join(g) for g in G]
