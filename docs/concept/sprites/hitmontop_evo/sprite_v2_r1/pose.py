    import sys
    m = masker()
    out = sys.argv[1]
    im = Image.fromarray(np.where(m[..., None] > 0, [40, 40, 40], [235, 235, 235]).astype('uint8'))
    im.save(out + '/pose_silhouet_1x.png')
