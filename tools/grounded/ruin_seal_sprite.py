MAP = {'.': 0, 'a': 10, 'b': 11, 'c': 12}


def sprite():
    rows = [r for r in RASTER.strip('\n').split('\n')]
    assert len(rows) == 32 and all(len(r) == 16 for r in rows), [len(r) for r in rows]
    im = Image.new('P', (16, 32), 0)
    px = im.load()
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            px[x, y] = MAP[ch] if ch in MAP else int(ch)
    flat = [v for c in PAL for v in c]
    im.putpalette(flat + [0] * (768 - len(flat)))
    return im


def main():
    im = sprite()
    im.save('graphics/object_events/pics/misc/ruin_seal.png')
    with open('graphics/object_events/palettes/ruin_seal.pal', 'w', newline='\r\n') as f:
        f.write('JASC-PAL\n0100\n16\n')
        for c in PAL + [(0, 0, 0)] * (16 - len(PAL)):
            f.write('%d %d %d\n' % c)
    if len(sys.argv) > 1:
        im.convert('RGB').resize((128, 256), Image.NEAREST).save(sys.argv[1])


if __name__ == '__main__':
    main()
