S(40,(21,'4'),(22,23,'5'),(24,26,'4'),(27,'3'),(28,37,'4'),(38,45,'3'))
S(41,(21,'4'),(22,23,'5'),(24,26,'4'),(27,'3'),(28,36,'4'),(37,44,'3'))
