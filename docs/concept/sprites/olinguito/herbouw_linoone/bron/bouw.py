FIJN2 = []   # alleen frame 2: rand van de verre klauw
# Rijen uitlijnen: spaties zijn typefouten -> verwijderen
def bouw(frame=1):
    can=[['.']*64 for _ in range(64)]
    for naam,x0,y0,rows in LAGEN:
        if frame==2 and naam=='voor_nabij': y0-=1   # frame 2: nabije voorpoot 1 px opgetild (stap)
        for dy,r in enumerate(rows):
            r=r.replace(' ','')
            for dx,ch in enumerate(r):
                if ch!='.': can[y0+dy][x0+dx]=ch
    for x,y,c in FIJN:
        can[y][x]=c
    if frame==2:
        for x,y,c in FIJN2: can[y][x]=c
    return [''.join(r) for r in can]
