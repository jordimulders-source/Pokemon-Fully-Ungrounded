def bouw():
    g = np.zeros((64, 64), int)
    for y, segs in R.items():
        for x0, s in segs:
            for i, c in enumerate(s):
                assert g[y, x0 + i] == 0, ('overlap', x0 + i, y)
                g[y, x0 + i] = int(c, 16)
    return g


def main():
    g = bouw()
    sil = np.array([[c == '#' for c in l.rstrip()] for l in open(os.path.join(HERE, '../silhouet_v2/direct_s1a.txt'))])
    teveel = np.argwhere((g > 0) & ~sil); tekort = np.argwhere((g == 0) & sil)
    print('alpha-diff met direct_s1a: teveel', [tuple(p[::-1]) for p in teveel], 'tekort', [tuple(p[::-1]) for p in tekort])
    open(os.path.join(HERE, 'ronde1.txt'), 'w').write('\n'.join(''.join('.' if v == 0 else format(v, 'x') for v in r) for r in g) + '\n')
    im = Image.new('P', (64, 64)); im.putpalette(sum(PALET, ())); im.putdata(g.flatten().tolist())
    im.save(os.path.join(HERE, 'ronde1.png'), transparency=0)
    # open randen: rand-pixel (naast transparant) dat geen omlijning/selout is
    rand_ok = {1, 2, 4, 8, 11}
    open_r = []
    for y, x in zip(*np.nonzero(g)):
        buren = [(y + dy, x + dx) for dy, dx in ((0, 1), (0, -1), (1, 0), (-1, 0))]
        if any(not (0 <= a < 64 and 0 <= b < 64) or g[a, b] == 0 for a, b in buren) and g[y, x] not in rand_ok:
            open_r.append((int(x), int(y), format(g[y, x], 'x')))
    print('open randen (rand niet 1/2/4/8/b):', open_r)
    los = [(int(x), int(y)) for y, x in zip(*np.nonzero(g)) if all(g[y + dy, x + dx] != g[y, x] for dy, dx in ((0, 1), (0, -1), (1, 0), (-1, 0)) if 0 <= y + dy < 64 and 0 <= x + dx < 64) and g[y, x] not in (1,)]
    print('losse pixels (geen buur met dezelfde kleur, excl. omlijning):', len(los), los)
    print('kleuren gebruikt:', sorted(set(g.flatten()) - {0}))


if __name__ == '__main__':
    main()
