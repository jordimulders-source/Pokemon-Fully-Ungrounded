# Ronde 3 lijf: met de hand opgegeven tonen per rij (x-bereiken), op basis 1s.
# Tonen: 5 licht, 4 basis, 3 schaduw, 2 omlijningsbasis/kern, 1 zwart.
from PIL import Image
B='../ronde1s/nachtaap_fase3.png'
src=Image.open(B); W=[list(''.join('.' if src.getpixel((x,y))==0 else '%X'%src.getpixel((x,y)) for x in range(64))) for y in range(64)]
old=[r[:] for r in W]
def S(y,*spans):
    for sp in spans:
        if len(sp)==2: x0,c=sp; x1=x0
        else: x0,x1,c=sp
        for x in range(x0,x1+1):
            assert W[y][x]!='.', (x,y)
            assert W[y][x] in '12345', (x,y,W[y][x])
            W[y][x]=c
# --- opgeheven been: lichtband doorlopend, dij waaiert uit in de lichte massa
S(16,(33,'5')); S(17,(33,'5')); S(23,(32,'5'))
S(28,(31,'5'))
S(29,(30,35,'5'),(36,37,'4'),(38,39,'3'))
# --- vuistarm: gekleurde rand boven (lichtkant), zwart onder (schaduwkant); lichtband tot in de schouder
S(19,(12,16,'2')); S(20,(17,18,'2')); S(21,(19,'2')); S(22,(20,'2')); S(23,(21,'2')); S(24,(21,'2')); S(25,(22,'2'))
