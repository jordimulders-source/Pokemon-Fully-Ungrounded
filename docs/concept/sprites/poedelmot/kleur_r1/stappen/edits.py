# Handmatige pixelbewerkingen bovenop rows.py. E = lijst (x,y,teken); R = regels op eigen raster.
E = []
def put(c, *pts):
    for x,y in pts: E.append((x,y,c))
def block(rows):  # {y: (x0, "tekens")}
    for y,(x0,s) in rows.items():
        for i,c in enumerate(s):
            if c!=' ': E.append((x0+i,y,c))
