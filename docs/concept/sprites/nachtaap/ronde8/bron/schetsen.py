def grid(txt):
    return [r for r in txt.strip('\n').split('\n')]


def paste(img, txt, ox, oy, scale):
    for y, row in enumerate(grid(txt)):
        for x, ch in enumerate(row):
            c = COL.get(ch)
            if c:
                for dy in range(scale):
                    for dx in range(scale):
                        img.putpixel((ox + x * scale + dx, oy + y * scale + dy), c + (255,))


